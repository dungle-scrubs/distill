def _noisy_dark_background() -> Image.Image:
    buffer = bytearray(WIDTH * HEIGHT * 3)
    index = 0
    for y in range(HEIGHT):
        for x in range(WIDTH):
            gradient = 23 + (8 * x // WIDTH) + (6 * y // HEIGHT)
            noise = ((x * 37 + y * 19 + (x * y) % 43) % 55) - 27
            value = max(0, min(255, gradient + noise))
            buffer[index : index + 3] = (
                value,
                value,
                max(0, min(255, gradient + noise + 7)),
            )
            index += 3
    return Image.frombytes("RGB", FRAME_SIZE, bytes(buffer))


def _low_contrast_disagreement(text: str) -> Image.Image:
    image = _noisy_dark_background()
    draw = ImageDraw.Draw(image)
    draw.multiline_text(
        (102, 275),
        text,
        font=_font(49),
        fill="#4a4a52",
        spacing=32,
    )
    return image


def _striped_background() -> Image.Image:
    image = Image.new("RGB", FRAME_SIZE, "#135260")
    draw = ImageDraw.Draw(image)
    stripe_width = 18
    for offset in range(-HEIGHT, WIDTH, stripe_width * 2):
        draw.polygon(
            (
                (offset, 0),
                (offset + stripe_width, 0),
                (offset + HEIGHT + stripe_width, HEIGHT),
                (offset + HEIGHT, HEIGHT),
            ),
            fill="#603051",
        )
    return image


def _striped_disagreement(text: str) -> Image.Image:
    image = _striped_background()
    text_layer = Image.new("RGBA", (1160, 300), (0, 0, 0, 0))
    text_draw = ImageDraw.Draw(text_layer)
    text_draw.multiline_text(
        (35, 70),
        text,
        font=_font(53, italic=True),
        fill="#dc0000",
        spacing=38,
    )
    rotated = text_layer.rotate(8, resample=Image.Resampling.BICUBIC, expand=True)
    image.paste(rotated, (55, 195), rotated)
    return image


def _dark_bokeh(_text: str) -> Image.Image:
    image = Image.new("RGB", FRAME_SIZE, "#080a0d")
    circles = Image.new("RGBA", FRAME_SIZE, (0, 0, 0, 0))
    draw = ImageDraw.Draw(circles)
    for bounds, fill in (
        ((-170, 80, 310, 560), (28, 40, 50, 150)),
        ((180, -190, 710, 340), (39, 31, 48, 125)),
        ((510, 150, 950, 590), (24, 43, 45, 145)),
        ((850, -80, 1390, 460), (43, 36, 29, 115)),
        ((920, 360, 1320, 760), (27, 32, 45, 135)),
        ((310, 430, 650, 770), (34, 29, 39, 105)),
    ):
        draw.ellipse(bounds, fill=fill)
    softened = circles.filter(ImageFilter.GaussianBlur(radius=72))
    return Image.alpha_composite(image.convert("RGBA"), softened).convert("RGB")


